# Python Variables and Data Types

# String variables
name = 'Saad'
print(f'Name: {name}')
print(f'Type: {type(name)}')

# Integer
age = 25
print(f'Age: {age}')
print(f'Type: {type(age)}')

# Float
height = 5.9
print(f'Height: {height}')
print(f'Type: {type(height)}')

# Boolean
is_student = True
print(f'Student: {is_student}')
print(f'Type: {type(is_student)}')

# Multiple assignment
x, y, z = 10, 20, 30
print(f'x={x}, y={y}, z={z}')

# Type conversion
num_str = '100'
num_int = int(num_str)
print(f'Converted: {num_int} (type: {type(num_int)})')

