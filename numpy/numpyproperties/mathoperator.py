import numpy as np

a = np.array([17, 25, 30])
print("Original array:", a)
print("Data type of the array:", a.dtype)
print("Size of the array:", a.size)
print("Shape of the array:", a.shape)
#Math operators
print("Sum of the array elements:", np.sum(a))
print("Mean of the array elements:", np.mean(a))
print(a + 5)
print(a - 5)
print(a * 5)
print(a ** 5)
print(a / 5)
